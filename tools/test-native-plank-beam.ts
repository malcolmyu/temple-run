import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import * as THREE from 'three';
import { OBJLoader } from 'three/addons/loaders/OBJLoader.js';
import { DEFS } from '../target/temple-run/web/src/game/obstacles/catalog';
import { collisionWouldHit } from '../target/temple-run/web/src/game/obstacles/collision';
const source=JSON.parse(readFileSync('target/temple-run/analysis/plank-beam-source.json','utf8'));
assert.deepEqual(source.flags,{MustJumpOver:true,MustSlideUnder:true,DoesKill:true});
const region=source.regions.find((r:any)=>r.pathID===15);
assert.equal(region.height,-8);
assert.deepEqual(DEFS.plankBeam.hitbox.z,[Math.min(...region.points.map((p:number[])=>p[1]))*.2,Math.max(...region.points.map((p:number[])=>p[1]))*.2]);
const ground=JSON.parse(readFileSync('target/temple-run/analysis/transition-region-source.json','utf8')).plankStraight.regions[0].heightOriginalUnits;
assert.ok(Math.abs(DEFS.plankBeam.hitbox.y[1]-(region.height-ground)*.2)<1e-8,'collision height is relative to native ground, not graphical deck normalization');
const obstacle={def:DEFS.plankBeam,lane:1,distance:681};
const runner={prevDistance:680.9,distance:681,laneIndex:1,side:0,jumpY:0,jumpV:0,slideRemaining:0,lastJumpAt:-10,lastSlideAt:-10,now:10,jumpWindow:1,slideWindow:.75};
assert.equal(collisionWouldHit(obstacle,runner),true);
assert.equal(DEFS.plankBeam.kill,true);
assert.equal(collisionWouldHit(obstacle,{...runner,slideRemaining:.5}),false);
assert.equal(collisionWouldHit(obstacle,{...runner,jumpY:1.5}),false);
assert.equal(collisionWouldHit(obstacle,{...runner,prevDistance:679,distance:679.5}),false);
const mesh=new OBJLoader().parse(readFileSync('target/temple-run/web/public/assets/obstacles/plank-beam.obj','utf8'));
mesh.traverse((o:any)=>{if(o.isMesh)o.material.side=THREE.DoubleSide;});mesh.updateMatrixWorld(true);
const bounds=new THREE.Box3().setFromObject(mesh);assert.ok(bounds.max.y>5&&bounds.max.y<6);
let floors=0;
for(let z=-5;z<5;z+=.1)if(new THREE.Raycaster(new THREE.Vector3(0,.3,z),new THREE.Vector3(0,-1,0),0,.6).intersectObject(mesh,true).some(h=>Math.abs(h.point.y)<.1))floors++;
assert.ok(floors>65,'full prefab supplies its own plank floor after base-tile replacement');
console.log('Native plank beam: source flags/Region2D, fatal standing contact, jump/slide escapes and original replacement floor.');
