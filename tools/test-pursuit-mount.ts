import assert from 'node:assert/strict';
import * as THREE from 'three';
import {mountPursuitRigs} from '../target/temple-run/web/src/game/pursuitMount';
import {buildChaser,type Assets} from '../target/temple-run/web/src/game/render';
const root=new THREE.Group();root.position.set(4,2,9);root.rotation.y=.7;root.scale.setScalar(1.12);
const sphere=new THREE.Mesh(new THREE.SphereGeometry());root.add(sphere);
mountPursuitRigs(root,[],8,[]);assert.equal(root.children.length,0);
const phases:number[]=[];
const rigs=Array.from({length:8},(_,i)=>({object:new THREE.Group(),setTime:(t:number)=>{phases[i]=t;}}));
const jumps=Array.from({length:8},(_,i)=>({y:i*.1}));
mountPursuitRigs(root,rigs,8,jumps,true);
assert.deepEqual(root.position.toArray(),[4,2,9]);assert.equal(root.rotation.y,.7);assert.equal(root.scale.x,1.12);
assert.equal(root.children[0].children.length,8);
rigs.forEach((r,i)=>{assert.equal(r.object.parent?.position.y,jumps[i].y);assert.equal(r.object.parent?.visible,i<3);assert.equal(phases[i],8+i*.11);});
mountPursuitRigs(root,rigs,0,jumps);assert.ok(root.children[0].children.every(c=>c.visible));assert.equal(root.children.length,1);
mountPursuitRigs(root,[],0,[]);assert.equal(root.children.length,0);
let meshes=0;buildChaser({} as Assets).traverse(o=>{if((o as THREE.Mesh).isMesh)meshes++;});assert.equal(meshes,0,'Missing enemy never becomes spheres');
sphere.geometry.dispose();(sphere.material as THREE.Material).dispose();
console.log('Pursuit late-mount: no proxy on failure, current anchor/phase/jumps preserved, eight rigs, restart visibility pass.');
