import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import * as THREE from 'three';
import {OBJLoader} from 'three/addons/loaders/OBJLoader.js';
import {DEFS} from '../target/temple-run/web/src/game/obstacles/catalog';
import {collisionWouldHit} from '../target/temple-run/web/src/game/obstacles/collision';
import {buildNativeFlame,updateNativeFlame} from '../target/temple-run/web/src/game/nativeFlame';
import source from '../target/temple-run/analysis/native-flame-tower-source.json';
assert.deepEqual(source.flags,{MustJumpOver:true,MustSlideUnder:true,DoesKill:true});
assert.equal(DEFS.flameTower.kill,true);assert.equal(DEFS.flameTower.lanes,'all');
assert.deepEqual(DEFS.flameTower.surfaceCut,[-6,6]);
assert.equal(DEFS.flameTower.hitbox.y[1],source.regions[1].height*.2);
const obstacle={def:DEFS.flameTower,lane:1,distance:20};
const runner={prevDistance:19.9,distance:20,laneIndex:1,side:0,jumpY:0,jumpV:0,slideRemaining:0,lastJumpAt:-10,lastSlideAt:-10,now:10,jumpWindow:1,slideWindow:.75};
assert.equal(collisionWouldHit(obstacle,runner),true,'standing centre lane is fatal');
assert.equal(collisionWouldHit(obstacle,{...runner,slideRemaining:.001}),false);
assert.equal(collisionWouldHit(obstacle,{...runner,jumpY:1.6}),false);
assert.equal(collisionWouldHit(obstacle,{...runner,lastSlideAt:9.9}),true,'expired slide does not receive invented grace');
assert.equal(collisionWouldHit(obstacle,{...runner,jumpY:.1,lastJumpAt:9.9}),true,'feet below native height cannot clear the plane');
const model=new OBJLoader().parse(readFileSync('target/temple-run/web/public/assets/obstacles/flame-tower.obj','utf8'));
const box=new THREE.Box3().setFromObject(model);assert.ok(box.min.z<-5.9&&box.max.z>5.9);
model.traverse((o:any)=>{if(o.isMesh)o.material.side=THREE.DoubleSide});model.updateMatrixWorld(true);
for(const z of [-5,0,5])assert.ok(new THREE.Raycaster(new THREE.Vector3(0,.4,z),new THREE.Vector3(0,-1,0),0,1).intersectObject(model,true).some(h=>Math.abs(h.point.y)<.1),'native prefab supplies floor');
const flame=buildNativeFlame(new THREE.Texture());const material=flame.material as THREE.MeshBasicMaterial;
assert.equal(flame.name,'native-flame');assert.deepEqual(flame.position.toArray(),source.position);
assert.equal(source.frames.length,10);assert.equal(source.fps,15);
updateNativeFlame(flame,1/15);assert.equal(material.map!.repeat.y,source.frames[1][3]/1024);
updateNativeFlame(flame,10/15);assert.equal(material.map!.repeat.y,source.frames[0][3]/1024);
assert.equal(material.fog,false);assert.equal(material.depthWrite,false);
console.log('Native flame: full TRS/floor, exact flag/height plane, strict jump/slide actions and10 original frames at15FPS.');

const rootSource=JSON.parse(readFileSync('target/temple-run/analysis/native-tree-slide-source.json','utf8'));
assert.deepEqual(rootSource.flags,{MustJumpOver:false,MustSlideUnder:true,DoesKill:true});
assert.equal(DEFS.treeSlide.kill,true);assert.deepEqual(DEFS.treeSlide.hitbox.z,[-.6,.6]);
const rootObstacle={def:DEFS.treeSlide,lane:1,distance:20};
assert.equal(collisionWouldHit(rootObstacle,runner),true);
assert.equal(collisionWouldHit(rootObstacle,{...runner,jumpY:4}),true,'slide-only root cannot be jumped through');
assert.equal(collisionWouldHit(rootObstacle,{...runner,slideRemaining:.001}),false);
assert.equal('surfaceCut'in DEFS.treeSlide,false,'tree OBJ excludes original road mesh; retain base floor');
